#!/bin/bash
# Install Git Hooks for Governance Framework
#
# This script installs the pre-commit governance hook into .git/hooks/
# Run this once after cloning the repository.

set -e

REPO_ROOT="$(git rev-parse --show-toplevel)"
HOOKS_DIR="$REPO_ROOT/.git/hooks"
GOVERNANCE_SCRIPT="$REPO_ROOT/scripts/pre_commit_governance.py"

echo "🔧 Installing Governance Hooks"
echo "================================"

# Verify governance script exists
if [ ! -f "$GOVERNANCE_SCRIPT" ]; then
    echo "❌ Error: Governance script not found at $GOVERNANCE_SCRIPT"
    exit 1
fi

# Make governance script executable
chmod +x "$GOVERNANCE_SCRIPT"
echo "✅ Governance script is executable"

# Create pre-commit hook
HOOK_FILE="$HOOKS_DIR/pre-commit"

cat > "$HOOK_FILE" << 'EOF'
#!/bin/bash
# Pre-Commit Governance Hook
# Auto-generated by scripts/install_hooks.sh

REPO_ROOT="$(git rev-parse --show-toplevel)"
GOVERNANCE_SCRIPT="$REPO_ROOT/scripts/pre_commit_governance.py"

# Run governance checks
python3 "$GOVERNANCE_SCRIPT"
exit_code=$?

# Exit with same code (0=allow, 1=block)
exit $exit_code
EOF

# Make hook executable
chmod +x "$HOOK_FILE"
echo "✅ Pre-commit hook installed at $HOOK_FILE"

# Test the hook
echo ""
echo "🧪 Testing hook installation..."
if python3 "$GOVERNANCE_SCRIPT" > /dev/null 2>&1; then
    echo "✅ Hook test passed"
else
    echo "⚠️  Hook test returned non-zero (this is OK if there are violations)"
fi

echo ""
echo "================================"
echo "✅ Governance hooks installed successfully"
echo ""
echo "The pre-commit hook will now:"
echo "  • Check SKILL.md files for LSP-first patterns"
echo "  • Require negative knowledge documentation"
echo "  • Enforce zero-context script pattern"
echo "  • Validate commit message format"
echo ""
echo "To bypass the hook (not recommended):"
echo "  git commit --no-verify"
echo ""
